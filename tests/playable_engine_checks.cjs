const assert = require('node:assert/strict');
const Board = require('../tools/playable/engine.js');
const b = new Board();
assert.deepEqual(b.matches(), [], 'no automatic opening matches');
const hinted=new Board();assert.ok(hinted.swap(...hinted.hint()).length,'hint produces a real match');
const before = [...b.cells];
assert.equal(b.swap(0,35),null);
assert.equal(b.swap(4,5),null);
assert.deepEqual(b.cells,before,'invalid swap rolls back');
assert.equal(b.moves,6);
const hit=b.swap(2,8);
assert.deepEqual(hit,[0,1,2]);
assert.equal(b.moves,5);
assert.equal(b.clear(hit).keys,3);
assert.equal(b.keys,3);
b.refill();assert.equal(b.cells.length,36);assert.ok(b.cells.every(v=>v>=0&&v<5));
const moves=b.moves;assert.equal(b.rocket().length,6);assert.equal(b.moves,moves,'tray rocket is free');assert.equal(b.rocket(),null,'single rocket supply');
b.reset();b.clear([0,1,2,3],true);assert.equal(b.cells[0],5,'four match creates rocket');
b.reset();b.moves=0;assert.equal(b.swap(2,8),null);
b.reset();assert.equal(b.keys,0);assert.equal(b.tray,1);
console.log('Playable rule checks passed.');
